  if (unmappedFrames.length > 0) {
    lines.push('### Unmapped Figma frames', '');
    lines.push('These frames are not yet assigned to a code component — review and assign:', '');
    for (const c of unmappedFrames) {
      lines.push(`- [ ] **${c.name}** (${CATEGORY_LABELS[c.functionalCategory]})`);
    }
    lines.push('');
  }

  // 1. Rename auto-generated state values
  lines.push('## 1. Rename Auto-Generated Property Values', '');
  lines.push('These components have Figma auto-names (`State2`, `Variant4`, etc.) that make it impossible to know what state is being represented.', '');

  const autoGenIssues: Array<{ component: string; axis: string; bad: string }> = [];
  for (const c of components) {
    for (const [axis, values] of Object.entries(c.properties)) {
      for (const v of values) {
        if (isInconsistentStateName(v)) {
          autoGenIssues.push({ component: c.name, axis, bad: v });
        }
      }
    }
  }
  for (const issue of autoGenIssues) {
    lines.push(`- [ ] **${issue.component}** — rename \`${issue.axis}=${issue.bad}\` to a descriptive value`);
  }

  // 2. Fix state axis pollution
  lines.push('', '## 2. Fix State Axis Pollution', '');
  lines.push('Values incorrectly placed in the `State` axis.', '');

  for (const c of components) {
    const stateValues = c.properties['State'] ?? [];
    const breakpointsInState = stateValues.filter((v) => NON_STATE_BREAKPOINTS.has(v));
    const inputTypesInState = stateValues.filter((v) => NON_STATE_INPUT_TYPES.has(v));
    const typosInState = stateValues.filter((v) => STATE_TYPOS[v]);

    for (const v of breakpointsInState) {
      lines.push(`- [ ] **${c.name}** — move \`State=${v}\` to the \`Size\` axis`);
    }
    for (const v of inputTypesInState) {
      lines.push(`- [ ] **${c.name}** — move \`State=${v}\` to the \`Style\` axis`);
    }
    for (const v of typosInState) {
      lines.push(`- [ ] **${c.name}** — rename \`State=${v}\` to \`State=${STATE_TYPOS[v]}\``);
    }
  }

  // 3. Deduplicate frames
  lines.push('', '## 3. Deduplicate Component Frames', '');
  lines.push('Components with duplicate names that appear twice in Figma:', '');
  const nameCounts = new Map<string, string[]>();
  for (const c of components) {
    if (!nameCounts.has(c.name)) nameCounts.set(c.name, []);
    nameCounts.get(c.name)!.push(c.figmaId);
  }
  let hasDuplicates = false;
  for (const [name, ids] of nameCounts.entries()) {
    if (ids.length > 1) {
      hasDuplicates = true;
      lines.push(`- [ ] **${name}** — appears ${ids.length} times (IDs: ${ids.join(', ')}) — delete or rename the duplicate`);
    }
  }
  if (!hasDuplicates) lines.push('No duplicates found. ✅');

