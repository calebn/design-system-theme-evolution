// Doc 01: Token Map (swatches fixed, Layout split into Font Sizes + Grid)
// ---------------------------------------------------------------------------

function doc01TokenMap(tokens: TokenCategory, gap: GapAnalysis): string {
  // Load Brand Styles audit for cross-referencing code-only colors
  const auditPath = join(ROOT, 'data', 'brand-styles-audit.json');
  const brandStylesHexes = new Set<string>();
  if (existsSync(auditPath)) {
    try {
      const audit = JSON.parse(readFileSync(auditPath, 'utf-8'));
      for (const item of audit.items ?? []) {
        if (item.extractedValue && item.extractedValue.startsWith('#')) {
          brandStylesHexes.add(item.extractedValue.toLowerCase());
        }
      }
    } catch {
      // ignore if audit file is malformed
    }
  }

  const lines: string[] = [
    '# 01 · Design Token Map',
    '',
    '> Generated from Figma Variables (`raw/figma-variables.json`).',
    '> DTCG tiers: **P** = Primitive · **S** = Semantic · **C** = Component.',
    '> Code match: ✅ matched in `commerce-theme` · ⚠️ Figma-only (needs code implementation) · — no data.',
    '',
  ];

  // Colors
  lines.push('## Colors', '');
  lines.push('| | Figma Name | Hex | Group | DTCG | Code Match | Code Key |');
  lines.push('|--|------------|-----|-------|------|------------|----------|');
  for (const t of tokens.colors) {
    const swatch = colorSwatch(t.rawValue);
    const matchEntry = gap.colors.matched.find((e) => e.figmaKey === t.figmaKey);
    const matchStr = matchEntry ? '✅ Matched' : gap.colors.figmaOnly.some((e) => e.figmaKey === t.figmaKey) ? '⚠️ Figma-only' : '—';
    const codeKey = matchEntry?.codeKey ?? '—';
    const tier = /primary|secondary|deep colors|bright/i.test(t.figmaKey) ? 'P' : 'S';
    lines.push(mdRow(swatch, `\`${t.figmaKey}\``, `\`${t.rawValue.toLowerCase()}\``, t.group, tier, matchStr, `\`${codeKey}\``));
  }

  if (gap.colors.codeOnly.length > 0) {
    const hasBrandStylesData = brandStylesHexes.size > 0;
    lines.push('', '### Colors in `commerce-theme` not referenced in Figma', '');
    lines.push('These exist in code but have no matching Figma variable. Candidates for removal or addition to Figma.', '');
    if (hasBrandStylesData) {
      lines.push('| | Code Key | Hex | Brand Styles? |');
      lines.push('|--|----------|-----|---------------|');
      for (const e of gap.colors.codeOnly) {
        const swatch = colorSwatch(e.codeValue ?? '#000');
        const inBrandStyles = brandStylesHexes.has((e.codeValue ?? '').toLowerCase()) ? '⚠️ Local style' : '—';
        lines.push(mdRow(swatch, `\`${e.codeKey}\``, `\`${e.codeValue}\``, inBrandStyles));
      }
    } else {
      lines.push('| | Code Key | Hex |');
      lines.push('|--|----------|-----|');
      for (const e of gap.colors.codeOnly) {
        const swatch = colorSwatch(e.codeValue ?? '#000');
        lines.push(mdRow(swatch, `\`${e.codeKey}\``, `\`${e.codeValue}\``));
      }
    }
  }

  // Typography
  lines.push('', '## Typography', '');
  lines.push('| Figma Name | Family | Weight | Line Height | Letter Spacing | Group |');
  lines.push('|------------|--------|--------|-------------|----------------|-------|');
  for (const t of tokens.typography) {
    const m = t.rawValue.match(/family:\s*"([^"]+)".*weight:\s*(\d+).*lineHeight:\s*([^,]+),.*letterSpacing:\s*([^)]+)/);
    if (m) {
      lines.push(mdRow(`\`${t.figmaKey}\``, m[1], m[2], m[3].trim(), m[4].trim(), t.group));
    }
  }

  // Font Sizes (separated from layout)
  if (tokens.fontSizes.length > 0) {
    lines.push('', '## Font Size References', '');
    lines.push('> These are numeric size values referenced by the typography composite tokens above.', '');
    lines.push('| Figma Name | Size (px) | Referenced By | Code Match |');
    lines.push('|------------|-----------|---------------|------------|');
    for (const t of tokens.fontSizes) {
      const typoRef = tokens.typography.find((ty) => ty.rawValue.includes(t.figmaKey));
      const refStr = typoRef ? `\`${typoRef.figmaKey}\`` : '—';
      const codeMatch = gap.typography.matched.some((e) => e.figmaKey === t.figmaKey);
      lines.push(mdRow(`\`${t.figmaKey}\``, `\`${t.rawValue}px\``, refStr, codeMatch ? '✅ Matched' : '—'));
    }
  }

  // Spacing
  lines.push('', '## Spacing', '');
  lines.push('| Figma Name | Value | Group | DTCG | Code Match | Code Key |');
  lines.push('|------------|-------|-------|------|------------|----------|');
  for (const t of tokens.spacing) {
    const isInComponent = /in component/i.test(t.figmaKey);
    const tier = isInComponent ? 'C' : 'S';
    const matchEntry = gap.spacing.matched.find((e) => e.figmaKey === t.figmaKey);
    const spMatch = matchEntry ? '✅ Matched' : gap.spacing.figmaOnly.some((e) => e.figmaKey === t.figmaKey) ? '⚠️ Figma-only' : '—';
    const codeKey = matchEntry?.codeKey ?? '—';
    lines.push(mdRow(`\`${t.figmaKey}\``, `\`${t.rawValue}px\``, t.group, tier, spMatch, `\`${codeKey}\``));
  }

  if (gap.spacing.codeOnly.length > 0) {
    lines.push('', '### Spacing in `commerce-theme` not in Figma', '');
    lines.push('| Code Key | Value |');
    lines.push('|----------|-------|');
    for (const e of gap.spacing.codeOnly) {
      lines.push(mdRow(`\`${e.codeKey}\``, `\`${e.codeValue}\``));
    }
  }

  // Shadows
  lines.push('', '## Shadows', '');
  lines.push('| Figma Name | First Layer | Code Match | Code Key |');
  lines.push('|------------|-------------|------------|----------|');
  for (const t of tokens.shadows) {
    const matchEntry = gap.shadows.matched.find((e) => e.figmaKey === t.figmaKey);
    const shadowMatch = matchEntry ? '✅ Matched' : '⚠️ Figma-only';
    const codeKey = matchEntry?.codeKey ?? '—';
    const firstEffect = t.rawValue.split(';')[0].trim().slice(0, 80);
    lines.push(mdRow(`\`${t.figmaKey}\``, `${firstEffect}...`, shadowMatch, `\`${codeKey}\``));
  }

  if (gap.shadows.codeOnly.length > 0) {
    lines.push('', '### Shadows in `commerce-theme` not in Figma', '');
    lines.push('| Code Key | First Layer |');
    lines.push('|----------|-------------|');
    for (const e of gap.shadows.codeOnly) {
      lines.push(mdRow(`\`${e.codeKey}\``, `${(e.codeValue ?? '').slice(0, 80)}...`));
    }
  }

  // Strokes
  lines.push('', '## Strokes (Border Widths)', '');
  lines.push('| Figma Name | Value |');
  lines.push('|------------|-------|');
  for (const t of tokens.strokes) {
    lines.push(mdRow(`\`${t.figmaKey}\``, `\`${t.rawValue}px\``));
  }

  // Layout & Grid (columns, viewport — NOT font sizes)
  lines.push('', '## Layout & Grid', '');
  lines.push('| Figma Name | Value | Group |');
  lines.push('|------------|-------|-------|');
  for (const t of tokens.layout) {
    lines.push(mdRow(`\`${t.figmaKey}\``, `\`${t.rawValue}\``, t.group));
  }

  lines.push('', '---', `*Generated by \`build-inventory.ts\`*`);
  return lines.join('\n');
}

