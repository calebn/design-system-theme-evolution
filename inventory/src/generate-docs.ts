export async function generateDocs() {
  console.log('\n=== generate-docs: generating markdown documents ===');

  const components: FigmaComponent[] = readJson('components.json');
  const axes: VariantAxis[] = readJson('variant-axes.json');
  const tokens: TokenCategory = readJson('tokens.json');
  const gap: GapAnalysis = readJson('gap-analysis.json');
  const taxonomy: Taxonomy = readJson('taxonomy.json');

  const docsDir = join(ROOT, 'docs');

  writeDoc(join(docsDir, '01-token-map.md'), doc01TokenMap(tokens, gap));
  writeDoc(join(docsDir, '02-component-inventory.md'), doc02ComponentInventory(components));
  writeDoc(join(docsDir, '03-state-matrix.md'), doc03StateMatrix(components));
  writeDoc(join(docsDir, '04-responsive-catalog.md'), doc04ResponsiveCatalog(components));
  writeDoc(join(docsDir, '05-variant-analysis.md'), doc05VariantAnalysis(components, axes, taxonomy.codeComponents));
  writeDoc(join(docsDir, '06-dependency-graph.md'), doc06DependencyGraph(components));
  writeDoc(join(docsDir, '07-priority-dashboard.md'), doc07PriorityDashboard(components, taxonomy));
  writeDoc(join(docsDir, '08-taxonomy.md'), doc08Taxonomy(components, taxonomy));
  writeDoc(join(docsDir, '09-component-architecture.md'), doc09ComponentArchitecture(components, taxonomy));
  writeDoc(join(docsDir, '10-figma-cleanup.md'), doc10FigmaCleanup(components, gap, taxonomy));
  writeDoc(join(docsDir, '12-component-surface-area.md'), doc12ComponentSurfaceArea(taxonomy, components));

  const auditPath = join(ROOT, 'data', 'brand-styles-audit.json');
  if (existsSync(auditPath)) {
    const audit = JSON.parse(readFileSync(auditPath, 'utf-8')) as BrandStylesAuditFile;
    writeDoc(join(docsDir, '11-design-token-migration.md'), doc11DesignTokenMigration(audit));
    console.log(`  doc 11 written (brand-styles audit found)`);
  }

  writeDoc(join(docsDir, 'README.md'), readme(components, tokens, gap, taxonomy));

  console.log(`  documents written to ./docs/`);
}

const isMain = process.argv[1]?.endsWith('generate-docs.ts') || process.argv[1]?.endsWith('generate-docs.js');
if (isMain) generateDocs().catch((e) => { console.error(e); process.exit(1); });
