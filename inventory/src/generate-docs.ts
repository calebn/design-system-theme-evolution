function doc10FigmaCleanup(components: FigmaComponent[], gap: GapAnalysis, taxonomy: Taxonomy): string {
  const codeComponents = taxonomy.codeComponents;

  const lines: string[] = [
    '# 10 · Figma Cleanup Checklist',
    '',
    '> Actionable items to improve Figma consistency before building components in code.',
    '> Check items off as you address them and re-run `npm run build` to verify.',
    '',
  ];

  // 0. Figma frames to code component mapping
  lines.push('## 0. Figma → Code Component Consolidation', '');
  lines.push('The following table shows which Figma frames will be collapsed into a single React component. Designers can optionally restructure Figma to reflect this hierarchy, but it is not required.', '');
  lines.push('| Code Component | Tier | Figma Frames |');
  lines.push('|----------------|------|--------------|');
  for (const cc of codeComponents) {
    lines.push(mdRow(`\`${cc.name}\``, TIER_LABELS[cc.tier], cc.figmaSources.join(', ')));
  }
  lines.push('');
  const unmappedFrames = components.filter((c) => !codeComponents.some((cc) => cc.figmaSources.includes(c.name)));
  if (unmappedFrames.length > 0) {
    lines.push('### Unmapped Figma frames', '');
    lines.push('These frames are not yet assigned to a code component — review and assign:', '');
    for (const c of unmappedFrames) {
      lines.push(`- [ ] **${c.name}** (${CATEGORY_LABELS[c.functionalCategory]})`);
    }
    lines.push('');
  }

  // 1. Rename auto-generated state values
  lines.push('## 1. Rename Auto-Generated Property Values', '');
  lines.push('These components have Figma auto-names (`State2`, `Variant4`, etc.) that make it impossible to know what state is being represented.', '');

  const autoGenIssues: Array<{ component: string; axis: string; bad: string }> = [];
  for (const c of components) {
    for (const [axis, values] of Object.entries(c.properties)) {
      for (const v of values) {
        if (isInconsistentStateName(v)) {
          autoGenIssues.push({ component: c.name, axis, bad: v });
        }
      }
    }
  }
  for (const issue of autoGenIssues) {
    lines.push(`- [ ] **${issue.component}** — rename \`${issue.axis}=${issue.bad}\` to a descriptive value`);
  }

  // 2. Fix state axis pollution
  lines.push('', '## 2. Fix State Axis Pollution', '');
  lines.push('Values incorrectly placed in the `State` axis.', '');

  for (const c of components) {
    const stateValues = c.properties['State'] ?? [];
    const breakpointsInState = stateValues.filter((v) => NON_STATE_BREAKPOINTS.has(v));
    const inputTypesInState = stateValues.filter((v) => NON_STATE_INPUT_TYPES.has(v));
    const typosInState = stateValues.filter((v) => STATE_TYPOS[v]);

    for (const v of breakpointsInState) {
      lines.push(`- [ ] **${c.name}** — move \`State=${v}\` to the \`Size\` axis`);
    }
    for (const v of inputTypesInState) {
      lines.push(`- [ ] **${c.name}** — move \`State=${v}\` to the \`Style\` axis`);
    }
    for (const v of typosInState) {
      lines.push(`- [ ] **${c.name}** — rename \`State=${v}\` to \`State=${STATE_TYPOS[v]}\``);
    }
  }

  // 3. Deduplicate frames
  lines.push('', '## 3. Deduplicate Component Frames', '');
  lines.push('Components with duplicate names that appear twice in Figma:', '');
  const nameCounts = new Map<string, string[]>();
  for (const c of components) {
    if (!nameCounts.has(c.name)) nameCounts.set(c.name, []);
    nameCounts.get(c.name)!.push(c.figmaId);
  }
  let hasDuplicates = false;
  for (const [name, ids] of nameCounts.entries()) {
    if (ids.length > 1) {
      hasDuplicates = true;
      lines.push(`- [ ] **${name}** — appears ${ids.length} times (IDs: ${ids.join(', ')}) — delete or rename the duplicate`);
    }
  }
  if (!hasDuplicates) lines.push('No duplicates found. ✅');

  // 4. Add missing critical states
  lines.push('', '## 4. Add Missing Critical States', '');
  lines.push('Components missing Hover, Focus, or Disabled states (minimum viable interactive states).', '');

  const missStates = ['Hover', 'Disabled'];
  for (const c of components) {
    const stateValues = (c.properties['State'] ?? []).map((v) => v.toLowerCase());
    if (stateValues.length === 0) continue;
    const missing = missStates.filter((s) => !stateValues.includes(s.toLowerCase()));
    if (missing.length > 0) {
      lines.push(`- [ ] **${c.name}** — add \`${missing.join(', ')}\` state variant(s)`);
    }
  }

  // 5. Reclassify "Other" section
  lines.push('', '## 5. Reclassify "Other" Section Components', '');
  lines.push('Move components out of the catch-all "Other" Figma section into their proper atomic sections.', '');
  const others = components.filter((c) => c.section === 'other');
  const reclassify: Record<string, string> = {
    'Badges and Tags': 'Atoms',
    'Price and Label': 'Atoms',
    'Sale Percentage': 'Atoms',
    'List': 'Atoms',
    'Product Images': 'Atoms',
    'Image Ratios': 'Consider removing — this is a layout constraint, not a component',
  };
  for (const c of others) {
    lines.push(`- [ ] **${c.name}** → move to **${reclassify[c.name] ?? 'Atoms'}** section`);
  }

  // 6. Standardize responsive coverage
  lines.push('', '## 6. Add Responsive Variants', '');
  lines.push('Key molecules/atoms that should have Desktop + Tablet + Mobile variants but currently do not.', '');

  const highPriorityForResponsive = ['Button', 'Text Input (single line)', 'Dropdown', 'Search Field', 'Toast Bar', 'Carousel Product', 'Product Content'];
  for (const name of highPriorityForResponsive) {
    const comp = components.find((c) => c.name === name);
    if (comp && !comp.hasResponsive) {
      lines.push(`- [ ] **${name}** — add Desktop, Tablet, Mobile size variants`);
    }
  }

  // 7. Token implementation gaps
  lines.push('', '## 7. Implement Missing Tokens in Code', '');
  lines.push('Figma variables that have no matching token in `commerce-theme`.', '');

  lines.push('', '**Colors (in Figma, not in code):**');
  for (const e of gap.colors.figmaOnly) {
    lines.push(`- [ ] Add \`${e.figmaKey}\` (\`${e.figmaValue}\`) to \`commerce-theme/src/colors.ts\``);
  }

  lines.push('', '**Spacing (in Figma, not in code):**');
  for (const e of gap.spacing.figmaOnly) {
    lines.push(`- [ ] Add \`${e.figmaKey}\` (\`${e.figmaValue}\`) to \`commerce-theme/src/spacing.ts\``);
  }

  lines.push('', '**Shadows (in Figma, not in code):**');
  for (const e of gap.shadows.figmaOnly) {
    lines.push(`- [ ] Add \`${e.figmaKey}\` to \`commerce-theme/src/shadows.ts\``);
  }

  // 8. Review code-only tokens
  lines.push('', '## 8. Audit Code-Only Tokens', '');
  lines.push('Tokens that exist in `commerce-theme` but have no Figma variable. These are either orphaned (remove) or missing from Figma (add variable).', '');

  if (gap.colors.codeOnly.length > 0) {
    lines.push('', '**Code-only colors:**');
    for (const e of gap.colors.codeOnly) {
      lines.push(`- [ ] \`${e.codeKey}\` (\`${e.codeValue}\`) — add to Figma or remove from \`colors.ts\``);
    }
  }

  if (gap.spacing.codeOnly.length > 0) {
    lines.push('', '**Code-only spacing:**');
    for (const e of gap.spacing.codeOnly) {
      lines.push(`- [ ] \`${e.codeKey}\` (\`${e.codeValue}\`) — add to Figma or remove from \`spacing.ts\``);
    }
  }

  lines.push('', '---', `*Generated by \`build-inventory.ts\`*`);
  return lines.join('\n');
}

