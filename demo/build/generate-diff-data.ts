/**
 * generate-diff-data.ts
 * Computes all version pair diffs and writes them to src/diff-data.ts
 * as a static import so the browser app doesn't need a Node.js runtime.
 */

import { runDiff } from './diff-tokens.js';
import { writeFileSync } from 'fs';
import { resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = fileURLToPath(new URL('.', import.meta.url));
const ROOT = resolve(__dirname, '..');

const VERSION_PAIRS = [
  ['1.0.0', '1.1.0'],
  ['1.1.0', '2.0.0'],
  ['1.0.0', '2.0.0'],
  ['1.0.0', 'current'],
  ['1.1.0', 'current'],
  ['2.0.0', 'current'],
] as const;

const diffData: Record<string, unknown> = {};

for (const [from, to] of VERSION_PAIRS) {
  const key = `${from}->${to}`;
  const result = runDiff(from, to) as {
    brands?: Array<{ changes?: Array<{ type: string }> }>;
    [k: string]: unknown;
  };
  // Strip "unchanged" entries — DiffPanel ignores them and they bloat the bundle
  if (result?.brands) {
    result.brands = result.brands.map((b) => ({
      ...b,
      changes: (b.changes ?? []).filter((c) => c.type !== 'unchanged'),
    }));
  }
  diffData[key] = result;
}

const output = `// AUTO-GENERATED by build/generate-diff-data.ts — do not edit
// Re-run: tsx build/generate-diff-data.ts

export const DIFF_DATA: Record<string, unknown> = ${JSON.stringify(diffData, null, 2)};
`;

writeFileSync(resolve(ROOT, 'src', 'diff-data.ts'), output);
console.log('✓ Generated src/diff-data.ts');
