// Color swatch using placehold.co image (renders on GitHub as a real colored square)
function colorSwatch(hex?: string): string {
  if (!hex || !hex.startsWith('#')) return '';
  const clean = hex.replace(/^#/, '').toUpperCase().padEnd(6, '0').slice(0, 6);
  return `![](https://placehold.co/12x12/${clean}/${clean}.png) `;
}

// Build a markdown table row with automatic pipe-escaping in every cell.
// Use this for ALL dynamic table rows — prevents pipe chars in TypeScript union
// types, Figma names, descriptions, etc. from breaking markdown table rendering.
function mdRow(...cells: string[]): string {
  return '| ' + cells.map((c) => c.replace(/\|/g, '\\|')).join(' | ') + ' |';
}

function matchStatus(figmaKey: string, gapColors: GapAnalysis['colors']): string {
  if (gapColors.matched.some((e) => e.figmaKey === figmaKey)) return '✅ Matched';
  if (gapColors.figmaOnly.some((e) => e.figmaKey === figmaKey)) return '⚠️ Figma-only';
  return '—';
}

// Detect auto-generated Figma state names
function isInconsistentStateName(val: string): boolean {
  return /^state\d+$/i.test(val) || /^variant\d+$/i.test(val) || /^property\s*\d+$/i.test(val);
}

// Values that appear in the State axis but are NOT interaction states
const NON_STATE_BREAKPOINTS = new Set(['Desktop', 'Tablet', 'Mobile']);
const NON_STATE_INPUT_TYPES = new Set(['Checkbox', 'Radio']);
const STATE_TYPOS: Record<string, string> = {
  'Focu': 'Focus',
  'Disable': 'Disabled',
  'Maxium': 'Maximum',
  'Focused': 'Focus (duplicate of "Focus")',
};

function classifyStateValue(val: string): 'valid' | 'breakpoint' | 'inputType' | 'typo' | 'autoGenerated' | 'nonStandard' {
  if (isInconsistentStateName(val)) return 'autoGenerated';
  if (NON_STATE_BREAKPOINTS.has(val)) return 'breakpoint';
  if (NON_STATE_INPUT_TYPES.has(val)) return 'inputType';
  if (STATE_TYPOS[val]) return 'typo';
  return 'valid';
}

