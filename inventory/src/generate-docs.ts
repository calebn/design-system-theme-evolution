interface PriorityScore {
  component: FigmaComponent;
  sectionScore: number;
  variantScore: number;
  stateScore: number;
  responsiveScore: number;
  depScore: number;
  total: number;
  recommendation: string;
}

function scorePriority(c: FigmaComponent, depWeight: Map<string, number>): PriorityScore {
  const sectionScore = c.section === 'atoms' ? 3 : c.section === 'inputs' ? 2 : c.section === 'molecules' ? 1 : 0;

  const stateValues = c.properties['State'] ?? c.properties['Property 1'] ?? [];
  const inconsistentCount = stateValues.filter((v) => isInconsistentStateName(v)).length;
  const variantScore = inconsistentCount === 0 ? 2 : Math.max(0, 2 - inconsistentCount);

  const hasDefaultStates =
    stateValues.some((v) => /default/i.test(v)) &&
    stateValues.some((v) => /hover/i.test(v)) &&
    stateValues.some((v) => /disabled?/i.test(v));
  const stateScore = hasDefaultStates ? 2 : stateValues.length > 0 ? 1 : 0;

  const responsiveScore = c.hasResponsive ? 1 : 0;

  // Dependency weight: how many other components depend on this one
  const dependents = depWeight.get(c.name) ?? 0;
  const depScore = dependents >= 3 ? 2 : dependents >= 1 ? 1 : 0;

  const total = sectionScore + variantScore + stateScore + responsiveScore + depScore;

  let recommendation: string;
  if (inconsistentCount > 0) {
    recommendation = '⚠️ Needs Figma cleanup (inconsistent state names)';
  } else if (total >= 7) {
    recommendation = '✅ Build first — high dependency weight';
  } else if (total >= 5) {
    recommendation = '✅ Ready to build';
  } else if (total >= 3) {
    recommendation = '🔄 Build with minor caveats';
  } else {
    recommendation = '⏳ Address coverage gaps first';
  }

  return { component: c, sectionScore, variantScore, stateScore, responsiveScore, depScore, total, recommendation };
}

interface CodeComponentScore {
  cc: CodeComponent;
  maxTotal: number;
  maxRecommendation: string;
  figmaFrameCount: number;
  hasCleanupNeeded: boolean;
  allDepCount: number;
}

function scoreCodeComponent(
  cc: CodeComponent,
  components: FigmaComponent[],
  depWeight: Map<string, number>
): CodeComponentScore {
  const sourceFrames = components.filter((c) => cc.figmaSources.includes(c.name));
  if (sourceFrames.length === 0) {
    return { cc, maxTotal: 0, maxRecommendation: '⏳ No Figma frames found', figmaFrameCount: 0, hasCleanupNeeded: false, allDepCount: 0 };
  }

  const frameScores = sourceFrames.map((c) => scorePriority(c, depWeight));
  const best = frameScores.reduce((a, b) => b.total > a.total ? b : a);

  // Aggregate dep count across all Figma sources
  const allDepCount = sourceFrames.reduce((sum, c) => sum + (depWeight.get(c.name) ?? 0), 0);
  const hasCleanupNeeded = frameScores.some((s) => s.recommendation.startsWith('⚠️'));

  let recommendation = best.recommendation;
  if (hasCleanupNeeded && !recommendation.startsWith('⚠️')) {
    recommendation = `${recommendation} (some frames need Figma cleanup)`;
  }

  return {
    cc,
    maxTotal: best.total,
    maxRecommendation: recommendation,
    figmaFrameCount: sourceFrames.length,
    hasCleanupNeeded,
    allDepCount,
  };
}

